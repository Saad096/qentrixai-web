p("Drop files into `public/images/<section>/<slug>.webp` and tell me; I will wire");
p("them up and generate the dark variants where they are needed.");
p();
p("---");
p();

function table(title, rows, note) {
  p(`## ${title}`);
  p();
  if (note) { p(note); p(); }
  p("| Route | What the page argues | What the image should show |");
  p("|---|---|---|");
  for (const r of rows) p(`| \`${r.route}\` | ${r.what} | ${r.image} |`);
  p();
}

