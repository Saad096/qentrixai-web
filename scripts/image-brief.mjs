/**
 * Generates IMAGE-BRIEF.md: every route, what the page argues, and what its
 * hero image needs to show.
 *
 * Written as a generator rather than a hand-kept document because the route
 * list comes from the data files. Add an industry and it appears here; the
 * brief cannot drift from the site.
 *
 *   node scripts/image-brief.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

/** Pull `field: "value"` pairs out of a data file without importing TS. */
function records(file, keys) {
  const src = readFileSync(file, "utf8");
  const out = [];
  const slugRe = /slug: "([^"]+)"/g;
  let m;
  const positions = [];
  while ((m = slugRe.exec(src))) positions.push({ slug: m[1], at: m.index });
  positions.forEach((p, i) => {
    const body = src.slice(p.at, positions[i + 1]?.at ?? src.length);
    const rec = { slug: p.slug };
    for (const k of keys) {
      // Quoted strings and template literals both appear in these files --
      // `image: \`${DIR}/x.webp\`` is the second kind, and missing it made
      // the brief claim ten industries had no photograph when they do.
      const q = new RegExp(`${k}:\\s*\\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(body);
      const t = new RegExp(`${k}:\\s*\\n?\\s*\\\`([^\\\`]*)\\\``).exec(body);
      if (q) rec[k] = q[1].replace(/\\"/g, '"');
      else if (t) rec[k] = t[1];
    }
    out.push(rec);
  });
  return out.filter((r) => !/^\$\{/.test(r.slug));
}

const services = records("src/data/services.ts", ["title", "short"]);
const industries = records("src/data/industries.ts", ["name", "line", "image"]);
const cases = records("src/data/caseStudies.ts", ["title", "category", "problem"]);
const products = records("src/data/products.ts", ["name", "tagline", "category"]);
const blogs = records("src/data/blogs.ts", ["title", "category", "excerpt"]);

const trim = (s, n = 155) => {
  if (!s) return "";
  const t = s.replace(/\s+/g, " ").trim();
  return t.length > n ? t.slice(0, n - 1).replace(/[ ,.;:]$/, "") + "…" : t;
};

