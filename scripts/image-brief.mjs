p("headline, so it should show the *subject of the page*, not the company.");
p();
p("**House style, so the set holds together:**");
p();
p("- **Line art or technical drawing**, not photography and not 3D renders, except");
p("  for the industry pages where a real photograph of the setting works better.");
p("- **Landscape 4:3** for hero cards (the home video is 3:4 because it sits beside");
p("  a three-line headline; everything else is wider).");
p("- **A subject, not a metaphor.** A drone over a crop row beats a glowing brain.");
p("- **No invented UI.** If it looks like a screenshot of a product, it will be read");
p("  as one. Diagrams and drawings are safe; fake dashboards are not.");
p("- **No vendor logos**, no recognisable faces, no client names.");
p("- Works on a warm graphite `#262621` ground and a stone `#E3E1D8` one. A drawing");
p("  on a transparent or near-white background needs a dark twin, or it glares.");
